#!/usr/bin/env node
// Train the Double-DQN stand-off follower shown in the "Hold the distance" demo, and score it
// against the tuned proportional controller. Node >= 18, no dependencies.
//
// Uses assets/js/demos/lib/standoff-core.js unchanged (the browser runs the same file):
//   * Trainer: Double DQN, 8-64-64-25 ReLU net, epsilon-greedy with held random actions, families and
//     stand-off d randomised per episode, greedy validation every 10 episodes on 9 fixed seeds, best
//     validation snapshot kept (early stopping).
//   * tuneP: grid search of the P gains on the same validation set and reward.
//   * Test suite: every trajectory family (3 trained on, 2 held out), N seeded episodes each, test
//     seeds disjoint from training and validation, identical conditions for both controllers.
// Writes assets/data/standoff-policy.json (weights rounded to 5 decimals; the suite is scored on the
// rounded weights, i.e. exactly what ships).
//
//   node tools/train_standoff.mjs                 # ~600 episodes
//   node tools/train_standoff.mjs --episodes 300 --out /tmp/x.json
import { createRequire } from 'module';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const require = createRequire(import.meta.url);
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const C = require(path.join(ROOT, 'assets/js/demos/lib/standoff-core.js'));

const args = Object.fromEntries(process.argv.slice(2).reduce((acc, a, i, all) => {
  if (a.startsWith('--')) acc.push([a.slice(2), all[i + 1]]);
  return acc;
}, []));
const EPISODES = Number(args.episodes ?? 600);
const SEED = Number(args.seed ?? 1);
const TEST_EPISODES = Number(args['test-episodes'] ?? 16);
const STANDOFF_M = 10;      // test stand-off distance (training randomises d in 6..16 m)
const NOISE = { noisePos_m: 0.1, noiseVel_mps: 0.05 };
const TEST_EPISODE_S = 40;
const OUT = args.out ?? path.join(ROOT, 'assets/data/standoff-policy.json');
const log = (s) => process.stdout.write(s + '\n');

// ---- train ----
const t0 = Date.now();
const tr = new C.Trainer({}, { seed: SEED, episode_s: 30, ...NOISE });
log(`Double DQN ${[C.OBS_DIM, ...C.DQN_DEFAULTS.hidden, C.ACTIONS.length].join('-')}, ${EPISODES} episodes, seed ${SEED}`);
let lastEval = 0;
while (tr.episode < EPISODES) {
  tr.step();
  if (tr.evals.length > lastEval) {
    lastEval = tr.evals.length;
    const e = tr.evals[tr.evals.length - 1], el = (Date.now() - t0) / 1000;
    log(`ep ${String(e.ep).padStart(5)}/${EPISODES}  steps ${tr.agent.steps}  eps ${tr.agent.epsilon.toFixed(3)}  ` +
      `val return ${e.ret.toFixed(1)}  val rms ${e.rms.toFixed(2)} m  failures ${e.failures}/9  ` +
      `best ep ${tr.best.ep} (${tr.best.ret.toFixed(1)})  ${el.toFixed(0)} s  ETA ${(el / tr.episode * (EPISODES - tr.episode)).toFixed(0)} s`);
  }
}
const trainWall = (Date.now() - t0) / 1000;

// ---- ship exactly the rounded best snapshot ----
const best = tr.best.net;
const round = (a) => a.map((v) => Math.round(v * 1e5) / 1e5);
const net = { sizes: best.sizes, W: best.W.map(round), b: best.b.map(round) };
const rl = C.MLP.fromJSON(net);

// ---- tune P on the validation set, then the test suite ----
const gains = C.tuneP(tr.valSet);
log(`P tuned on validation: Kp ${gains.Kp}, Kv ${gains.Kv} (return ${gains.ret.toFixed(1)})`);
const families = [...C.TRAIN_FAMILIES, ...C.HELDOUT_FAMILIES];
const suite = {};
for (const [fi, fam] of families.entries()) {
  const cfgs = Array.from({ length: TEST_EPISODES }, (_, i) => ({ family: fam, seed: C.SEED_BASE.test + fi * 1000 + i,
    standoff_m: STANDOFF_M, episode_s: TEST_EPISODE_S, ...NOISE }));
  const p = C.summarize(cfgs.map((c) => C.runEpisode(new C.PController(gains.Kp, gains.Kv, true), c)));
  const r = C.summarize(cfgs.map((c) => C.runEpisode(new C.RLController(rl), c)));
  const pick = (s) => ({ ret: +s.ret.toFixed(2), rms_m: +s.rms_m.toFixed(3), in_band: +s.inBand.toFixed(3),
    max_err_m: +s.maxErr_m.toFixed(2), min_range_frac: +s.minRange_frac.toFixed(2), effort_mps2: +s.effort_mps2.toFixed(2),
    failures: s.failures, n: s.n });
  suite[fam] = { label: C.FAMILIES[fam].label, split: C.FAMILIES[fam].split, p: pick(p), rl: pick(r) };
  log(`${C.FAMILIES[fam].label.padEnd(18)} ${C.FAMILIES[fam].split.padEnd(8)}  ` +
    `P: rms ${p.rms_m.toFixed(2)} m, in band ${(100 * p.inBand).toFixed(0)}%, failures ${p.failures}/${p.n}   ` +
    `RL: rms ${r.rms_m.toFixed(2)} m, in band ${(100 * r.inBand).toFixed(0)}%, failures ${r.failures}/${r.n}`);
}

const out = {
  about: 'Double-DQN stand-off follower for assets/js/demos/standoff.js. Generated by tools/train_standoff.mjs.',
  net,
  params: net.W.reduce((n, w) => n + w.length, 0) + net.b.reduce((n, b) => n + b.length, 0),
  training: { method: 'Double DQN (Polyak target, Huber loss, Adam), epsilon-greedy with held random actions; ' +
      'best greedy-validation snapshot', episodes: EPISODES, best_episode: tr.best.ep, env_steps: tr.agent.steps,
    updates: tr.agent.updates, seed: SEED, cfg: C.DQN_DEFAULTS, wall_s: Math.round(trainWall) },
  // tuneP searches Kp in 0.2..2.0 and Kv in 0.5..3.0 (standoff-core.js); a best value on the edge means a
  // wider search might find a stronger baseline, and the demo card says so.
  p_gains: { Kp: gains.Kp, Kv: gains.Kv, drag_ff: true, tuned_on: 'same 9 validation episodes and reward as the agent',
    grid: { Kp: [0.2, 2.0], Kv: [0.5, 3.0] }, at_grid_edge: gains.Kp === 2.0 || gains.Kv === 3.0 },
  test: { standoff_m: STANDOFF_M, episode_s: TEST_EPISODE_S, settle_s: C.SETTLE_S, episodes_per_family: TEST_EPISODES,
    noise: NOISE, seeds: `${C.SEED_BASE.test} + 1000 * family index + i`, in_band: '|range - d| <= 0.1 d after the settle window',
    families: suite },
};
fs.writeFileSync(OUT, JSON.stringify(out));
log(`wrote ${OUT} (${fs.statSync(OUT).size} bytes); training ${trainWall.toFixed(0)} s`);
